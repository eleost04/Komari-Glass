export function CarrierIcon({
  carrier,
  className,
}: {
  carrier?: string;
  className?: string;
}) {
  const key = String(carrier || "").toLowerCase();
  if (key.includes("telecom") || key.includes("电信") || key.includes("ct")) {
    return <TelecomIcon className={className} />;
  }
  if (key.includes("mobile") || key.includes("移动") || key.includes("cm")) {
    return <MobileIcon className={className} />;
  }
  if (key.includes("unicom") || key.includes("联通") || key.includes("cu")) {
    return <UnicomIcon className={className} />;
  }
  return (
    <span
      className={`size-2 rounded-full bg-primary/60 ${className || ""}`}
      aria-hidden="true"
    />
  );
}
